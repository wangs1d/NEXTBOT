/**
 * 注册开机自启（仅 Windows）：今日简报等定时能力依赖服务端常驻。
 * 优先创建当前用户"登录时"计划任务（隐藏窗口、无执行时限、登录延迟 15s 等网络），
 * 无管理员权限创建失败时退回 HKCU Run 键（功能等价）。
 * 用法：npm run autostart:install
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(SCRIPT_DIR, "..", "..");

const TASK_NAME = "NextbotServer";
const RUN_VALUE_NAME = "NextbotServer";
// 桌面 App 自启（计划任务触发，绕开 Run 键串行排队）
const APP_TASK_NAME = "NextbotApp";
// App 设置页「开机自启」开关的 Run 值名（FlutterWindow::setAutoStart 写入）
const APP_RUN_VALUE_NAME = "Nextbot";
const STARTUP_APPROVED_RUN_KEY =
  "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\StartupApproved\\Run";
// 旧版名（2026-10-23 前的注册名），注册成功后顺带清理，避免双重拉起
const LEGACY_TASK_NAME = "PrivateAgentServer";
const LEGACY_RUN_VALUE_NAME = "PrivateAgentServer";
const RUN_KEY = "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run";
// 登录后延迟启动：等桌面/网络栈就绪，避免开机竞态
const LOGON_DELAY_S = 15;

if (process.platform !== "win32") {
  console.error("仅支持 Windows；macOS/Linux 请用 launchd/systemd 实现同等能力。");
  process.exit(1);
}

const vbsPath = path.join(SCRIPT_DIR, "autostart-launcher.vbs");

/**
 * 固定自启使用的 Node 可执行文件。
 *
 * 本机 better-sqlite3 是按 Node 22 预编译的；若从 Node 24 的终端执行
 * `npm run autostart:install`，直接用 process.execPath 会把 VBS 重新烘成 24，
 * 下次登录又回到 NODE_MODULE_VERSION 崩溃循环。因此重装时优先复用上一次
 * 烘进 VBS 的 Node 路径，其次才回退到当前进程的 Node。
 */
function readBakedNodeExe() {
  try {
    const vbs = fs.readFileSync(vbsPath, "utf8");
    return vbs.match(/sh\.Run\s+"""([^"\r\n]+?node\.exe)""/i)?.[1] ?? null;
  } catch {
    return null;
  }
}

function resolveNodeExe() {
  const override = process.env.NEXTBOT_NODE_EXE?.trim();
  if (override && fs.existsSync(override)) return override;

  const baked = readBakedNodeExe();
  if (baked) {
    if (fs.existsSync(baked)) return baked;
    console.warn(`⚠ 已固定的 Node 路径不存在，回退到当前 Node：${baked}`);
  }
  return process.execPath;
}

const nodeExe = resolveNodeExe();
const wscriptExe = path.join(process.env.SystemRoot ?? "C:\\Windows", "System32", "wscript.exe");
const launcherScript = path.join(SCRIPT_DIR, "autostart-server.mjs");
const appVbsPath = path.join(SCRIPT_DIR, "app-launcher.vbs");
const appLauncherScript = path.join(SCRIPT_DIR, "app-launcher.mjs");
if (!fs.existsSync(launcherScript)) {
  console.error(`未找到启动器：${launcherScript}`);
  process.exit(1);
}
if (!fs.existsSync(appLauncherScript)) {
  console.error(`未找到桌面端启动器：${appLauncherScript}`);
  process.exit(1);
}

// 生成 VBS 壳：wscript 以窗口样式 0 运行，登录拉起时全程无黑色控制台闪现
const vbsQuote = (s) => s.replace(/"/g, '""');
fs.writeFileSync(
  vbsPath,
  [
    "' 由 install-autostart.mjs 生成（含本机绝对路径，勿手工编辑；重装自启会覆盖）",
    'Set sh = CreateObject("WScript.Shell")',
    `sh.CurrentDirectory = "${vbsQuote(ROOT)}"`,
    `sh.Run """${vbsQuote(nodeExe)}"" ""${vbsQuote(launcherScript)}""", 0, False`,
    "",
  ].join("\r\n"),
  "utf8",
);
// App 启动器壳：保持纯 ASCII，wscript 按 ANSI 解析 .vbs，中文注释会吞换行
fs.writeFileSync(
  appVbsPath,
  [
    "' Generated by install-autostart.mjs (machine-specific paths; do not hand-edit)",
    'Set sh = CreateObject("WScript.Shell")',
    `sh.CurrentDirectory = "${vbsQuote(ROOT)}"`,
    `sh.Run """${vbsQuote(nodeExe)}"" ""${vbsQuote(appLauncherScript)}""", 0, False`,
    "",
  ].join("\r\n"),
  "utf8",
);

function runPs(script) {
  const encoded = Buffer.from(script, "utf16le").toString("base64");
  return spawnSync(
    "powershell.exe",
    ["-NoProfile", "-ExecutionPolicy", "Bypass", "-EncodedCommand", encoded],
    { windowsHide: true, encoding: "utf8" },
  );
}

function registerTask() {
  const user = `${process.env.USERDOMAIN ?? ""}\\${process.env.USERNAME ?? ""}`;
  const ps = [
    `$action = New-ScheduledTaskAction -Execute '${wscriptExe}' -Argument '"${vbsPath}"'`,
    `$trigger = New-ScheduledTaskTrigger -AtLogOn -User '${user}'`,
    `$trigger.Delay = 'PT${LOGON_DELAY_S}S'`,
    `$principal = New-ScheduledTaskPrincipal -UserId '${user}' -LogonType Interactive -RunLevel Limited`,
    "$settings = New-ScheduledTaskSettingsSet -ExecutionTimeLimit ([TimeSpan]::Zero) -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)",
    `Register-ScheduledTask -TaskName '${TASK_NAME}' -Action $action -Trigger $trigger -Principal $principal -Settings $settings -Description 'NextBot 服务端开机自启（今日简报等定时任务依赖）' -Force | Out-Null`,
    "Write-Output '__REGISTER_OK__'",
  ].join("; ");
  const r = runPs(ps);
  return r.status === 0 && (r.stdout ?? "").includes("__REGISTER_OK__");
}

function registerAppTask() {
  const user = `${process.env.USERDOMAIN ?? ""}\\${process.env.USERNAME ?? ""}`;
  const ps = [
    `$action = New-ScheduledTaskAction -Execute '${wscriptExe}' -Argument '"${appVbsPath}"'`,
    `$trigger = New-ScheduledTaskTrigger -AtLogOn -User '${user}'`,
    `$principal = New-ScheduledTaskPrincipal -UserId '${user}' -LogonType Interactive -RunLevel Limited`,
    "$settings = New-ScheduledTaskSettingsSet -ExecutionTimeLimit (New-TimeSpan -Minutes 10) -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew",
    `Register-ScheduledTask -TaskName '${APP_TASK_NAME}' -Action $action -Trigger $trigger -Principal $principal -Settings $settings -Description 'NextBot 桌面 App 登录自启（计划任务触发，绕开 Run 键串行排队）' -Force | Out-Null`,
    "Write-Output '__REGISTER_OK__'",
  ].join("; ");
  const r = runPs(ps);
  return r.status === 0 && (r.stdout ?? "").includes("__REGISTER_OK__");
}

// 计划任务接管 App 启动后，禁用 Run 键直启。Windows 逐个执行 Run 项且每个
// 常驻进程最多等 30s（Shell-Core 9707/9708），NEXTBOT 排在后面 → 登录后
// 约 2 分钟才启动，还会把已启动的窗口再前置一次。
// 这里只写 Windows 自己的 StartupApproved 开关，Run 值本身保留——它仍是
// App 设置页「开机自启」的状态来源（app-launcher 据此决定是否拉起）。
function disableRunKeyLaunch() {
  const r = spawnSync(
    "reg.exe",
    [
      "add",
      STARTUP_APPROVED_RUN_KEY,
      "/v",
      APP_RUN_VALUE_NAME,
      "/t",
      "REG_BINARY",
      "/d",
      "030000000000000000000000",
      "/f",
    ],
    { windowsHide: true, encoding: "utf8" },
  );
  return r.status === 0;
}

function registerRunKey() {
  const data = `"${wscriptExe}" "${vbsPath}"`;
  const r = spawnSync("reg.exe", ["add", RUN_KEY, "/v", RUN_VALUE_NAME, "/t", "REG_SZ", "/d", data, "/f"], {
    windowsHide: true,
    encoding: "utf8",
  });
  return r.status === 0;
}

function removeRunKey(valueName = RUN_VALUE_NAME) {
  spawnSync("reg.exe", ["delete", RUN_KEY, "/v", valueName, "/f"], { windowsHide: true, stdio: "ignore" });
}

function removeTask(taskName = TASK_NAME) {
  spawnSync("schtasks.exe", ["/end", "/tn", taskName], { windowsHide: true, stdio: "ignore" });
  spawnSync("schtasks.exe", ["/delete", "/tn", taskName, "/f"], { windowsHide: true, stdio: "ignore" });
}

console.log(`固定 Node：${nodeExe}${nodeExe === process.execPath ? "（当前进程）" : "（沿用已安装路径）"}`);
console.log("正在注册开机自启…");
if (registerTask()) {
  // 此前若用过 Run 键方式（含旧版注册名），清理残留避免双重拉起
  removeRunKey();
  removeRunKey(LEGACY_RUN_VALUE_NAME);
  removeTask(LEGACY_TASK_NAME);
  console.log(`✓ 已创建计划任务「${TASK_NAME}」：每次登录后 ${LOGON_DELAY_S} 秒隐藏启动服务端栈`);
} else if (registerRunKey()) {
  removeTask();
  removeTask(LEGACY_TASK_NAME);
  console.log("✓ 已写入当前用户 Run 键：登录后隐藏启动服务端栈");
  console.log("  （计划任务创建失败，通常因缺少管理员权限；Run 键方式功能等价）");
} else {
  console.error("✗ 计划任务与 Run 键均注册失败，请用管理员权限重试：npm run autostart:install");
  process.exit(1);
}

// 桌面 App：计划任务直拉，避免 Run 键排队（实测可提前约 80s）
if (registerAppTask()) {
  const blocked = disableRunKeyLaunch();
  console.log(`✓ 已创建计划任务「${APP_TASK_NAME}」：登录后立即等后端就绪，再拉起桌面 App`);
  if (blocked) {
    console.log("  已禁用 Run 键直启（App 设置页的开机自启状态不受影响）");
  } else {
    console.log("  ⚠ 禁用 Run 键直启失败，登录后可能再被 Run 队列晚拉一次（单实例会复用窗口）");
  }
} else {
  console.log("⚠ 桌面 App 计划任务创建失败，继续沿用 App 自写的 Run 键（会受 Run 队列阻塞约 2 分钟）");
}

console.log("  拉起内容：scripts/autostart/autostart-server.mjs（默认 dev 模式，与 npm run dev:all 一致；");
console.log("  端口已占用自动跳过，崩溃自动退避重启）。生产模式见 README「开机自启」一节。");
console.log(`  立即验证：schtasks /run /tn ${TASK_NAME}；查看状态：npm run autostart:status`);
