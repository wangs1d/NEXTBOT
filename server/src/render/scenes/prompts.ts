import { DISPLAY_EFFECT_TYPES } from "@nextbot/agent-protocol";

/**
 * 天气轮边界（2026-11-14 主流口径改写）：正文是回答本身，卡片只是视觉补充。
 *
 * 旧口径（2026-10-08 起）是「数值由卡片承载、正文不许复述/不许表格」——等于用
 * 服务端规则替模型决定回答形态，用户点名字表格也拿不到（真机取证）。豆包这类
 * 主流做法是：工具结果进上下文，模型按用户要求把回答写完整，组件/卡片只做增强，
 * 永远不替代文字回答。这里只保留事实与安全边界。
 */
export const WEATHER_CARD_BOUNDARY =
  `天气轮：按用户要的形态把天气信息回答完整——问结论就给结论，要看表格就用 markdown 表格逐日列出（数据取回执里的 dailyForecast），要清单就列清单；` +
  `详略也按用户说的来，不要用「数值在卡片里」把用户挡回去。系统可能另附一张概览卡，那只是视觉补充，不替代你的回答。` +
  `严禁向用户展示经纬度坐标数字（如 35.68, 139.77）——坐标仅供工具入参，位置只说城市/区域名，解析不出就不提位置。` +
  `建议只能基于回执里的事实（气温/降水/天气现象）与用户本轮明说的上下文；` +
  `用户没提过的具体行为场景（骑车/开车/跑步/洗晒等）不要替用户虚构，拿不准就不写。`;

/**
 * 明日预览边界（2026-11-09 改口径）：数据以事实块注入，正文由模型自己写。
 * 旧口径「已由系统渲染，只补一句提醒」随 rewritesText 一并作废。
 */
export const TOMORROW_PREVIEW_BOUNDARY =
  `明日预览：下面是系统掌握的明天真实数据（日期/行程/天气/到期/近期），` +
  `只是一个骨架，不是要你照抄的版式。用你自己的话把明天讲给用户，连贯口语，` +
  `可以先说最要紧的那件；要点说全，不要编造未列出的项，同一件事不要重复说。`;

/**
 * 提醒确认轮边界（2026-11-14 主流口径）：正文是回答本身，确认卡只是视觉补充。
 * 只保留内容边界（别重复他刚说的时刻、别提内部编排），不规定版式。
 */
export const REMINDER_CONFIRM_BOUNDARY =
  `提醒轮：时间、日期、事项按用户要的形态说清楚（一句话、清单、表格都行），系统可能另附一张确认卡做视觉补充。` +
  `用户刚说过的时刻不要重复播报；不要提内部编排（系统/后台/分级/生效）。` +
  `没定成功时如实说明原因并给下一步，不要预告「正在设置」。`;

/**
 * 盘点清单边界（2026-11-14 主流口径）：条目是事实来源，正文由模型按用户要求组织；
 * 只保留事实边界（不编造、不吐 JSON），不限制表格/清单/分节。
 */
export const DIGEST_ROUNDUP_BOUNDARY =
  `盘点轮：下面是本轮检索到的真实条目。据此把这几件事讲清楚——可以合并同类、点出最值得注意的一条；` +
  `不要编造条目之外的任何事实，不要输出 JSON；用户要表格/清单/逐条对比就按他要的形态整理。`;

/** 结构卡可用 cardType（唯一来源：display-effects 枚举 + 权限引导卡） */
export const RESULT_CARD_TYPES: readonly string[] = [
  ...DISPLAY_EFFECT_TYPES.filter((t) => t !== ""),
  "permission_request",
];

/** 结构卡载荷 schema（字段级，无版式描述） */
export const RESULT_CARD_CONTRACT =
  `[AGENT_RESULT_CARD_START]{"cardType":"${RESULT_CARD_TYPES.join("|")}",` +
  `"title":"≤20字","items":[{"type":"num|warn","text":"条目文本","url":"可选"}],"footer":"可选"}` +
  `[AGENT_RESULT_CARD_END]`;
