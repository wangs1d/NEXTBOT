const T2S_MAP = new Map<string, string>();
for (const token of T2S_PAIRS.split(/\s+/)) {
  if (token.length !== 2) continue; // 防御：异常 token 直接丢弃，不影响其余映射
  T2S_MAP.set(token[0]!, token[1]!);
}
const T2S_KEYS = [...T2S_MAP.keys()].join("");
const T2S_RE = new RegExp(`[${T2S_KEYS}]`, "g");

/**
 * 繁→简 1:1 等长替换。无繁体字符时零接触（返回原串、changed=false）。
 * 纯字符级替换：不改写、不重排、不删字节——对协议块/Markdown/URL 均无副作用
 * （映射字不会出现在 URL/ASCII 里）。
 */
export function normalizeTraditionalToSimplified(text: string): {
  text: string;
  changed: boolean;
} {
  if (!text) return { text, changed: false };
  T2S_RE.lastIndex = 0;
  const out = text.replace(T2S_RE, (c) => T2S_MAP.get(c) ?? c);
  return out === text ? { text, changed: false } : { text: out, changed: true };
}

/** 测试/探针用：映射表规模 */
export function t2sMapSize(): number {
  return T2S_MAP.size;
}
