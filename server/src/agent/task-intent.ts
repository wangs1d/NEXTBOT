// Agent — TaskIntent（任务执行意图的"单一来源"判定）
//
// 收敛背景：本模块是 brain 侧（rule-router/DecisionHub）的"泛化任务意图"判定源。
// 2026-10-21 去路由化后，执行平面由主模型原生 tool_calls 决定，
// 本判定只服务于 brain 内部的诊断路由与工作记忆管理，不参与执行平面决策。
//
// 设计原则：
//   - 只认「祈使结构」这类高精度信号：祈使引导词（帮我/请/麻烦/给我…）是
//     "要我做某事"的确定性标志，误判率极低；不含祈使的句子交给模型自决。
//   - 不做"动作动词 + 长度"式的泛化猜测——那类信号无法区分「帮我做X」和
//     「(我)在做X/这不是在做X吗」，是词表打地鼠的根源（见下方 2026-10-21 收紧）。
//
// 2026-10-21 收紧（真机事故根修）：原规则「动作动词 + 长度 ≥ 10 → 任务」已删除。
// 该规则不看句式，陈述/调侃/反问里只要含动作动词词根即命中——「哎呀 这不是在做
// 独立开发吗 我要追我老婆呀」因名词短语「独立开发」被判成任务，经 forced-tool 的
// tool_choice=required 放大为「API 层强制调工具」，模型被迫把闲聊里提到的实体当
// 查询需求去搜（答非所问的根源）。去路由化后「这轮要不要用工具」由模型原生
// tool_calls 自决（task-router.ts 契约），本判定只保留祈使结构这一高精度信号，
// 服务于 brain 诊断路由与 planner 升级判定——两者误判代价对称（宁可漏判，漏了
// 还有模型自决与出口闸兜底；误判则是强制动作，不可逆）。
//
// 本判定不替代域名关键词（转账/下单/写代码/部署/桌面自动化等），那些精确且强意作法保留在原处。

// 强"做某事"动作动词（任务句式里常见核心动词；无需穷举，祈使结构兜底）
const ACTION_VERB_RE =
  /整理|归纳|归类|分类|排序|分组|重命名|归档|下载|上传|导入|导出|转换|压缩|解压|打包|解包|合并|拆分|分割|拼接|剪辑|翻译|改写|润色|润饰|校对|重写|概括|总结|摘要|生成|制作|创建|新建|撰写|起草|设计|策划|拟定|做成|画|绘|设置|设定|配置|修改|调整|取消|删除|清除|重置|启用|禁用|开通|备份|恢复|迁移|同步|清理|美化|优化|升级|发送|发给|分享|转发|推送|截图|录屏|采集|抓取|收集|搜集|统计|汇总|修复|调试|重构|搭建|开发|实现|安装|卸载|解析|分析|对比|比价|核验|验证|校验|调研|查看|看看|安排|筹备|预约|制定|规划/i;

// 祈使句式引导词：明确"要我做某事"
const IMPERATIVE_RE =
  /帮我|帮我把|请帮我|请把|麻烦|帮我一下|拜托|帮我处理|帮我弄|帮我搞|给我|去帮忙|帮忙/i;

// 实时单一查询（由 fast 的简单工具循环覆盖）→ 不应判为任务
const REALTIME_ONLY_RE =
  /现在.*几点|几点了|今天(?:的)?天气|天气(?:怎么|如何|怎么样|如何)|星期几|今天.*几号|当前.*时间|你叫什么|你是谁/i;

// 纯提问句式（以问词引导）→ 交 fast 正常作答
const QUESTION_OPENING_RE =
  /^(?:什么是|啥是|为什么|为何|怎么[样么一]|如何|能不能|会不会|有没有|是不是|要不要|在哪里|哪个更好|选哪个|几点)/;

// 寒暄/简短闲聊 → 保留 fast
const CASUAL_SHORT_RE =
  /^(?:在吗|还在吗|哈哈|haha|lol|嗯|嗯嗯|好的|哦|噢|喔|行|好嘞|收到|谢谢你|辛苦啦|睡了吗|吃了吗|ok|okay)[呼号。．、？！?,!\s]*$/i;

// 纯知识问答 / 概念解释（无需任何工具即可作答）→ 交 fast，不判为任务。
// 覆盖"帮我解释一下X区别 / 讲讲 / 介绍一下 / 原理 / 是什么意思"这类纯口头问答；
// 不含"看看/查查/整理/下载"等需要取料的动作，避免把真实任务误放回 fast。
const KNOWLEDGE_QA_RE =
  /帮我解释|解释[一下一]?|讲[一]?下|讲讲|介绍一下|怎么理解|的区别|的原理?|意味着什么|什么是|是什么|指的是|啥意思|什么意思|为什么.*?(?:会|能|要|这么)/i;

/**
 * 判定消息是否为"要做某事"的可执行任务（brain 诊断路由 / planner 升级判定）。
 *
 * 返回 true 的判定路径（只认祈使结构，不猜话题）：
 *   1. 祈使引导词 + 动作动词 → 明确任务；
 *   2. 祈使句式本身（无需枚举动词，如"帮我把这个搞定"）→ 任务。
 * 非祈使句（陈述/调侃/反问）一律 false——要不要用工具由模型自决。
 */
export function isActionableTaskRequest(message: string): boolean {
  const t = (message ?? "").trim();
  if (!t) return false;

  // 1) 寒暄 / 纯提问 / 实时单一查询 / 纯知识问答优先排除（这些保留 fast）
  if (CASUAL_SHORT_RE.test(t)) return false;
  if (QUESTION_OPENING_RE.test(t)) return false;
  if (REALTIME_ONLY_RE.test(t)) return false;
  if (KNOWLEDGE_QA_RE.test(t)) return false;

  const imperative = IMPERATIVE_RE.test(t);
  const verbHit = ACTION_VERB_RE.test(t);

  // 1) 祈使 + 动作动词 → 明确任务
  if (imperative && verbHit) return true;
  // 2) 祈使句式本身（动词超出枚举也命中）→ 任务
  if (imperative && t.length >= 8) return true;

  return false;
}

// 零工具隔离安全网（2026-10-07）：纯闲聊轮硬隔离（routeIntent==="chat" → 零工具）
// 的误判代价被真机实证为不可接受——「帮我看看明天的天气」「一分钟后提醒我去吃饭」
// 被路由小模型判进闲聊，模型一个工具都看不见，只能嘴硬"没有天气接口/没法定时"。
// 本词表只干一件事：命中即**禁止**本轮零工具隔离（工具恢复可见），不改变路由平面、
// 不强制派发；误命中代价仅是闲聊轮看得见工具（隔离前的常态）。宁窄勿滥。
const ZERO_TOOL_UNSAFE_RE =
  /天气|气温|降雨|下雪|提醒|闹钟|几点|现在时间|今天几号|明天几号|日期|星期几|日程|快递|账单|余额|帮我查|帮我看看|帮我搜|帮我找|查一下|查查|搜一下|搜索|打电话|发消息|发条消息|下单|点外卖|叫车/i;

/** 命中即禁止本轮「纯闲聊零工具隔离」（见 ZERO_TOOL_UNSAFE_RE 注释）。 */
export function turnNeedsToolFloor(message: string): boolean {
  const t = (message ?? "").trim();
  return t.length > 0 && ZERO_TOOL_UNSAFE_RE.test(t);
}